/**
 * 敵の迂回（ステアリング。M7-4a。ADR-043）の数値。手触りの調整はここだけを触る。
 *
 * 進みたい向き（目標へ）の先が障害物に塞がれていたら、向きを少しずつ回して、体が通れる向きを選ぶ。
 * 柱・岩・壁・箱のような単純な障害物なら、これで回り込める（凹んだ地形・迷路は経路探索が要る = ダンジョン M9）。
 */
export const STEERING = {
  /** 先を見る距離（m。体の中心から測る）。これより先の障害物は、近づいてから避け始める */
  lookahead: 2.4,
  /** 向きを回す候補（度。小さい順）。小さい角度で通れる向きが優先され、塞がれるほど大きく回る。最後の 130° は、壁に沿って横へ滑り出す向き */
  offsetsDeg: [20, 40, 60, 80, 100, 130],
  /** 体の幅を測るときに、触れているだけで「塞がれている」としないための余裕（m）。障害物に接して押し出された体が、どの向きにも進めなくならないように */
  slack: 0.05,
  /** 始点が太らせた障害物の中（接している）でも、外向き・沿う向きなら通れるとして、先へ進めて調べ直す幅（m） */
  skip: 0.12,
  /** 目標がこれより近いなら迂回しない（攻撃の距離。壁越しに触れているときなどに向きを乱さない） */
  minDistance: 0.4,
} as const;
